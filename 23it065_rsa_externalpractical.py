"""Step 2: Settings and Imports"""

import torch, numpy as np, pandas as pd
import torch.nn as nn, torch.nn.functional as F
import matplotlib.pyplot as plt
from torch.utils.data import TensorDataset, DataLoader
from opacus import PrivacyEngine

torch.manual_seed(42)
np.random.seed(42)
device = "cpu"

DELTA = 1e-5
MAX_GRAD_NORM = 1.0
BATCH_SIZE = 256
EPOCHS = 3

"""Step 3: Import Dataset"""

TRAIN_FILE = "/content/sample_data/mnist_train_small.csv"
TEST_FILE  = "/content/sample_data/mnist_test.csv"

def load_csv(path):
    df = pd.read_csv(path, header=None)
    if not str(df.iloc[0, 0]).replace(".", "").isdigit():
        df = pd.read_csv(path)
    y = torch.tensor(df.iloc[:, 0].values, dtype=torch.long)
    x = torch.tensor(df.iloc[:, 1:].values, dtype=torch.float32) / 255.0
    x = (x - 0.1307) / 0.3081
    return x.view(-1, 1, 28, 28), y

X_train, y_train = load_csv(TRAIN_FILE)
X_test,  y_test  = load_csv(TEST_FILE)
X_train, y_train = X_train[:20000], y_train[:20000]

print("Train:", X_train.shape, " Test:", X_test.shape)

train_loader = DataLoader(TensorDataset(X_train, y_train),
                          batch_size=BATCH_SIZE, shuffle=True)

"""Step 4: Model CNN"""

class SmallCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 16, 3, padding=1)
        self.gn1   = nn.GroupNorm(4, 16)
        self.conv2 = nn.Conv2d(16, 32, 3, padding=1)
        self.gn2   = nn.GroupNorm(8, 32)
        self.fc1   = nn.Linear(32 * 7 * 7, 64)
        self.fc2   = nn.Linear(64, 10)

    def forward(self, x):
        x = F.max_pool2d(F.relu(self.gn1(self.conv1(x))), 2)
        x = F.max_pool2d(F.relu(self.gn2(self.conv2(x))), 2)
        x = x.flatten(1)
        x = F.relu(self.fc1(x))
        return self.fc2(x)

def evaluate(model, X, y):
    """returns accuracy (%) and mean max-softmax confidence"""
    model.eval()
    with torch.no_grad():
        probs = F.softmax(model(X), dim=1)
    acc = (probs.argmax(1) == y).float().mean().item() * 100
    conf = probs.max(1).values.mean().item()
    return acc, conf

def train_one_epoch(model, optimizer, loader):
    model.train()
    for xb, yb in loader:
        optimizer.zero_grad()
        loss = F.cross_entropy(model(xb), yb)
        loss.backward()
        optimizer.step()

"""Step 5: Task 1 - Test Accuracy"""

torch.manual_seed(42)
baseline = SmallCNN()
opt = torch.optim.Adam(baseline.parameters(), lr=1e-3)

for ep in range(EPOCHS):
    train_one_epoch(baseline, opt, train_loader)

base_acc, _ = evaluate(baseline, X_test, y_test)
print(f"Baseline (no DP) : test accuracy {base_acc:.1f} %")

"""Step 6: Task 2 - DP training for ε = 10, 5, 1"""

def train_dp_target_eps(target_eps):
    torch.manual_seed(42)
    model = SmallCNN()
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)
    pe = PrivacyEngine()
    model, optimizer, loader = pe.make_private_with_epsilon(
        module=model, optimizer=optimizer, data_loader=train_loader,
        target_epsilon=target_eps, target_delta=DELTA,
        epochs=EPOCHS, max_grad_norm=MAX_GRAD_NORM)
    for ep in range(EPOCHS):
        train_one_epoch(model, optimizer, loader)
    acc, _ = evaluate(model, X_test, y_test)
    eps_spent = pe.get_epsilon(DELTA)
    return model, acc, eps_spent

results = {}
dp_models = {}
for eps in [10.0, 5.0, 1.0]:
    m, acc, spent = train_dp_target_eps(eps)
    results[eps] = (acc, spent)
    dp_models[eps] = m

print(f"Baseline (no DP) : test accuracy {base_acc:.1f} %\n")
print("TARGET_EPS  DELTA   CLIP(C)  EPOCHS  TEST_ACC  EPS_SPENT")
print("-" * 58)
for eps, (acc, spent) in results.items():
    print(f"{eps:<11} {DELTA:<7} {MAX_GRAD_NORM:<8} {EPOCHS:<7} {acc:.1f} %    {spent:.2f}")
print("-" * 58)
print(f"Accuracy cost of strongest privacy (eps = 1): {results[1.0][0] - base_acc:.1f} %")

"""Step 7: Task 3 - fixed noise_multiplier = 1.1, ε after each epoch"""

torch.manual_seed(42)
model_nm = SmallCNN()
opt_nm = torch.optim.Adam(model_nm.parameters(), lr=1e-3)
pe_nm = PrivacyEngine()
model_nm, opt_nm, loader_nm = pe_nm.make_private(
    module=model_nm, optimizer=opt_nm, data_loader=train_loader,
    noise_multiplier=1.1, max_grad_norm=MAX_GRAD_NORM)

eps_per_epoch = []
for ep in range(EPOCHS):
    train_one_epoch(model_nm, opt_nm, loader_nm)
    eps_per_epoch.append(pe_nm.get_epsilon(DELTA))

print("FIXED noise_multiplier = 1.1")
print("EPOCH  EPSILON_SPENT")
print("-" * 21)
for i, e in enumerate(eps_per_epoch, 1):
    print(f"{i:<6} {e:.2f}")

"""Step 8: Task - 4 membership-inference check"""

def conf_gap(model):
    _, tr_conf = evaluate(model, X_train, y_train)
    _, te_conf = evaluate(model, X_test, y_test)
    return tr_conf, te_conf, tr_conf - te_conf

print("MEMBERSHIP CHECK (mean max-softmax confidence)")
print("MODEL        TRAIN   TEST    GAP")
print("-" * 36)
for name, m in [("Baseline", baseline), ("DP (eps=1)", dp_models[1.0])]:
    tr, te, gap = conf_gap(m)
    print(f"{name:<12} {tr:.3f}   {te:.3f}   {gap:.3f}")

